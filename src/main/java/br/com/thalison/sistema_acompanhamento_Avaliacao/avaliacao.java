package br.com.thalison.sistema_acompanhamento_Avaliacao;

/** Avaliação de um aluno (tabela avaliacao), registrada pelo professor. */
public class avaliacao {

    private int id;
    private int alunoId;
    private int disciplinaId;
    private String nomeDisciplina;
    private String tipo;
    private String descricao;
    private double nota;
    private String data;
    private String observacao;

    public avaliacao() {
    }

    public avaliacao(int id, String descricao, double nota,
                     String data, String observacao) {
        this.id = id;
        this.descricao = descricao;
        this.nota = nota;
        this.data = data;
        this.observacao = observacao;
    }

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public int getAlunoId() {
        return alunoId;
    }

    public void setAlunoId(int alunoId) {
        this.alunoId = alunoId;
    }

    public int getDisciplinaId() {
        return disciplinaId;
    }

    public void setDisciplinaId(int disciplinaId) {
        this.disciplinaId = disciplinaId;
    }

    public String getNomeDisciplina() {
        return nomeDisciplina;
    }

    public void setNomeDisciplina(String nomeDisciplina) {
        this.nomeDisciplina = nomeDisciplina;
    }

    public String getTipo() {
        return tipo;
    }

    public void setTipo(String tipo) {
        this.tipo = tipo;
    }

    public String getDescricao() {
        return descricao;
    }

    public void setDescricao(String descricao) {
        this.descricao = descricao;
    }

    public double getNota() {
        return nota;
    }

    public void setNota(double nota) {
        this.nota = nota;
    }

    public String getData() {
        return data;
    }

    public void setData(String data) {
        this.data = data;
    }

    public String getObservacao() {
        return observacao;
    }

    public void setObservacao(String observacao) {
        this.observacao = observacao;
    }
}
